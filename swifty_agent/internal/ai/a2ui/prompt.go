// Package a2ui implements the server side of the A2UI v0.9 tag protocol:
// the system prompt section that teaches the LLM to optionally emit ONE
// <a2ui-json> block after its markdown answer, tag extraction from complete
// and streamed LLM output, structural validation of the message list, and a
// one-shot corrective retry for invalid blocks.
//
// Full protocol validation happens client-side with the @a2ui/web_core zod
// schemas; the Go checks are structural only — enough to reject malformed
// blocks early and to drive the corrective retry.
package a2ui

import (
	"encoding/json"
	"fmt"
)

const (
	// OpenTag and CloseTag delimit the A2UI block in LLM output.
	OpenTag  = "<a2ui-json>"
	CloseTag = "</a2ui-json>"

	// CatalogID mirrors the client-side catalog id (src/catalog/index.ts in
	// swifty-agent-fe); duplicated on purpose since the catalog is client-only.
	CatalogID = "https://a2ui.org/specification/v0_9/catalogs/basic/catalog.json"

	// UIActionPrefix marks chat messages the client synthesizes from surface
	// actions; the prompt teaches the LLM how to handle them.
	UIActionPrefix = "[UI_ACTION]"
)

type m = map[string]any

// The few-shot examples are generated by builders so UI structure changes
// only need a builder edit — the prompt stays in sync automatically.

